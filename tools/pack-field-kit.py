"""Pack the field kit into a classic script the toys load.

Reads lib/field/kit.json and the WAVs beside it, encodes each clip to MP3
(128 kbit/s, mono, 44.1 kHz, through ffmpeg on PATH) and writes
lib/field-kit-data.js: base64 inside a plain <script>, because a page opened
straight off a disk may not fetch() and may load a script tag. GROUNDING.md,
"Shipped material must survive clone-and-double-click".

    python tools/pack-field-kit.py

Run it after any change to lib/field/ (a WAV, a trim, the mapping). The data
file is committed with the material.
"""
import base64
import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
FIELD = ROOT / 'lib' / 'field'
OUT = ROOT / 'lib' / 'field-kit-data.js'


def mp3(wav):
    # -map_metadata -1 and -write_xing 0 keep the bytes a function of the audio
    # alone, so regenerating from unchanged WAVs gives an unchanged file
    cmd = ['ffmpeg', '-hide_banner', '-loglevel', 'error', '-i', str(wav),
           '-ac', '1', '-ar', '44100', '-c:a', 'libmp3lame', '-b:a', '128k',
           '-map_metadata', '-1', '-id3v2_version', '0', '-write_xing', '0',
           '-f', 'mp3', '-']
    r = subprocess.run(cmd, capture_output=True)
    if r.returncode != 0:
        sys.exit('ffmpeg failed on %s:\n%s' % (wav.name, r.stderr.decode(errors='replace')))
    return r.stdout


def main():
    kit = json.loads((FIELD / 'kit.json').read_text(encoding='utf-8'))
    clips = []
    for c in kit:
        data = mp3(FIELD / c['file'])
        clips.append({'id': c['id'], 'name': c['name'], 'standsFor': c['standsFor'],
                      'trim_db': c['trim_db'], 'mime': 'audio/mpeg',
                      'b64': base64.b64encode(data).decode('ascii')})
        print('%-14s -> %-8s %7d bytes mp3' % (c['id'], c['standsFor'], len(data)))
    head = ('/* GENERATED by tools/pack-field-kit.py from lib/field/kit.json and the\n'
            '   WAVs in lib/field/ — do not edit; change the material and re-run it.\n'
            '   Eight field recordings by Jean-Philippe Drecourt, CC0 with the\n'
            '   collection, as base64 MP3 so the kit survives a page opened from disk.\n'
            '   Lab.fieldKit (lib/field-kit.js) decodes them. */\n')
    body = ',\n'.join('  ' + json.dumps(c, ensure_ascii=False) for c in clips)
    js = (head + 'window.Lab = window.Lab || {};\n'
          'Lab.fieldKitData = { clips: [\n' + body + '\n] };\n')
    OUT.write_text(js, encoding='utf-8', newline='\n')
    print('wrote %s (%d bytes)' % (OUT.relative_to(ROOT), len(js.encode('utf-8'))))


if __name__ == '__main__':
    main()
