"use strict";
/* ============================================================
   Lab.fieldKit — the second kit: eight field recordings standing
   in for the ids each clip names (the drum set, and a few of the
   render voices), behind one switch every page inherits.

   Needs audio.js, voices.js, samples.js and field-kit-data.js
   loaded before it. The data is base64 MP3 inside a classic
   script (generated by tools/pack-field-kit.py from lib/field/),
   decoded here unconditionally at load: one path on every
   protocol, file:// included.

   Either kit plays, never a mix: use(true) stands a recording in
   for every id the data names, use(false) gives every one of them
   its own sound back. The choice is lib-wide in localStorage, so
   it follows a visitor from toy to toy.

   Each buffer is trimmed to its onset and its tail (MP3 padding,
   which differs by browser) and scaled by its trim_db, the loudness match to the
   quietest clip. Lab.voices.play then sounds it at the call's gain
   or at unity, never at the synth's defaults.gain.
   ============================================================ */
window.Lab = window.Lab || {};

Lab.fieldKit = (function () {
  const KEY = 'lab:kit';
  const data = Lab.fieldKitData;

  if (!data || !data.clips || !Lab.samples || !Lab.voices) {
    console.warn('Lab.fieldKit: ' + (!data ? 'field-kit-data.js is not loaded'
                 : 'samples.js and voices.js must load before field-kit.js') +
                 ' — the page keeps its drums.');
    return null;
  }

  let on = false;                 // the kit the page is sounding
  let buffers = {};               // drum id -> trimmed, scaled AudioBuffer
  const views = [];               // switches built by control(), repainted on change

  function stored() {
    try { return localStorage.getItem(KEY) === 'field'; } catch (e) { return false; }
  }
  function store(v) {
    try { localStorage.setItem(KEY, v ? 'field' : 'drums'); } catch (e) { /* no storage */ }
  }

  function scale(buf, db) {
    const g = Math.pow(10, (db || 0) / 20);
    if (g === 1) return buf;
    for (let ch = 0; ch < buf.numberOfChannels; ch++) {
      const d = buf.getChannelData(ch);
      for (let i = 0; i < d.length; i++) d[i] *= g;
    }
    return buf;
  }

  // A clip may stand in for several ids; one buffer serves them all.
  function idsOf(c) { return [].concat(c.standsFor || []); }

  const ready = Promise.all(data.clips.map(function (c) {
    const ids = idsOf(c);
    return Lab.samples.decodeBase64(c.b64).then(function (buf) {
      if (!buf) { console.warn('Lab.fieldKit: ' + c.id + ' did not decode — ' + ids.join(', ') +
                               ' keep their own sound.'); return; }
      const b = scale(Lab.samples.trimTail(Lab.samples.trimLead(buf)), c.trim_db);
      ids.forEach(function (id) { buffers[id] = b; });
    }).catch(function (e) {
      console.warn('Lab.fieldKit: ' + c.id + ' failed (' + e + ') — ' + ids.join(', ') +
                   ' keep their own sound.');
    });
  })).then(function () { return buffers; });

  function apply() {
    data.clips.forEach(function (c) {
      idsOf(c).forEach(function (id) {
        Lab.voices.standIn(id, on ? (buffers[id] || null) : null);
      });
    });
    views.forEach(function (paint) { paint(); });
  }

  // Sets and stores the choice; the kit stands in once it has decoded.
  function use(v) {
    on = !!v;
    store(on);
    views.forEach(function (paint) { paint(); });
    return ready.then(function () { apply(); return on; });
  }

  function active() { return on ? 'field' : 'drums'; }

  /* The switch, in the bench's two-state idiom: a button whose face is the
     value, named by the label beside it. It shapes what sounds and does not
     start the audio, which is why it belongs in the master strip's
     `controls`, where Lab.page puts it on every page that loads this file. */
  const SAYS = 'that is the sounds switch — drums or field recordings. It shapes what sounds.';

  function control() {
    const b = document.createElement('button');
    b.type = 'button';
    function paint() {
      b.textContent = on ? 'field' : 'drums';
      b.setAttribute('aria-pressed', on ? 'true' : 'false');
      b.setAttribute('aria-label', 'sounds ' + b.textContent);
    }
    // a press while the kit is still decoding waits for it, then flips
    b.addEventListener('click', function () { ready.then(function () { use(!on); }); });
    views.push(paint);
    paint();
    const HINT = 'drums or field recordings; your choice follows you to the other toys';
    return Lab.ui.inline('sounds', b, HINT);
  }

  // The stored choice, applied without writing it back: anything but 'field'
  // is drums, a garbage value included.
  on = stored();
  ready.then(apply);

  return { ready: ready, use: use, active: active, control: control, says: SAYS };
})();
